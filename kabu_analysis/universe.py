def get_universe(sectors: list[str] | None = None) -> list[Stock]:
    """ユニバース全銘柄(またはセクター指定)を返す。重複コードは初出のセクターを採用。"""
    seen: set[str] = set()
    stocks: list[Stock] = []
    for sector, entries in _UNIVERSE.items():
        if sectors and sector not in sectors:
            continue
        for ticker, name in entries:
            if ticker in seen:
                continue
            seen.add(ticker)
            stocks.append(Stock(ticker=ticker, name=name, sector=sector))
    return stocks


def all_sectors() -> list[str]:
    return list(_UNIVERSE.keys())


def find_stock(query: str) -> Stock | None:
    """コード(例: "7203"/"7203.T")または銘柄名の部分一致でユニバースを検索。"""
    q = query.strip()
    code = q.upper().removesuffix(".T")
    for stock in get_universe():
        if stock.ticker.removesuffix(".T") == code:
            return stock
    for stock in get_universe():
        if q in stock.name:
            return stock
    return None
